"""Helpers for writing tests.py files.

Expected outputs are generated by running the problem's reference solution (solution.py),
so you normally only describe the INPUTS here.

    from engine.spec import fn, cls

    def tests():
        return [
            fn("Example 1", "two_sum", [2, 7, 11, 15], 9),
            cls("Basic ops", "LRUCache", [2], [["put", [1, 1]], ["get", [1]]]),
        ]

    def scale(n):                      # optional: enables the Complexity button
        return fn(f"n={n}", "two_sum", list(range(n)), n)

    SCALE = {"sizes": [1000, 2000, 4000, 8000, 16000, 32000], "label": "n = len(nums)"}

Options (keyword args on fn/cls):
    tag      "Part 1" | "Follow-up" | "Part 2" | "Stretch" ...  (Stretch only runs on Submit)
    hidden   True -> input is hidden in the UI and only runs on Submit
    float    True -> numbers compared with 1e-6 tolerance
    compare  "unordered" -> top-level list order doesn't matter
             "unordered_deep" -> also sorts nested lists' order at the top level
    expected give the answer yourself (skips running the reference; use for very slow cases)
"""


def _opts(d, kw):
    d["tag"] = kw.pop("tag", "Part 1")
    d["hidden"] = kw.pop("hidden", False)
    for k in ("float", "compare", "expected", "n"):
        if k in kw:
            d[k] = kw.pop(k)
    if kw:
        raise TypeError(f"unknown options: {sorted(kw)}")
    return d


def fn(name, call, *args, **kw):
    """A test that calls a top-level function: call(*args)."""
    return _opts({"name": name, "kind": "function", "call": call, "args": list(args)}, kw)


def cls(name, cls_name, init, ops, **kw):
    """A test that builds cls_name(*init) then runs each [method, [args]] in ops.
    Expected = list of return values, one per op (None for methods that return nothing)."""
    return _opts({"name": name, "kind": "class", "cls": cls_name, "init": list(init),
                  "ops": [[m, list(a)] for m, a in ops]}, kw)
